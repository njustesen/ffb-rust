"""Generate crates/ffb-model/src/model/property/named_property_names.rs from Java's NamedProperties.

Java `NamedProperty.getName()` is the display string the client sees (e.g. in
`Player.temporaryPropertiesMap`); the Rust `NamedProperties` constants hold the Java FIELD name
(camelCase). This table maps one to the other. Rerun after the Java NamedProperties changes:
    python -I scripts/gen_named_property_names.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
JAVA = os.path.join(REPO, "..", "ffb-java", "ffb", "ffb-common", "src", "main", "java", "com", "fumbbl",
                    "ffb", "model", "property", "NamedProperties.java")
OUT = os.path.join(REPO, "crates", "ffb-model", "src", "model", "property", "named_property_names.rs")

src = open(JAVA, encoding="utf-8").read()
pairs = re.findall(r'public static final \w+ (\w+)\s*=\s*new (?:NamedProperty|PassingProperty)\(\s*"([^"]*)"', src, re.S)
pairs.sort()
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// @generated by scripts/gen_named_property_names.py from Java NamedProperties -- do not edit.\n")
    f.write("//! Java field name (the Rust `NamedProperties` constant value) -> `NamedProperty.getName()`.\n\n")
    f.write("/// (field name, Java display name), sorted by field name.\n")
    f.write("pub const NAMED_PROPERTY_NAMES: &[(&str, &str)] = &[\n")
    for k, v in pairs:
        f.write(f"    ({json.dumps(k)}, {json.dumps(v)}),\n")
    f.write("];\n")
print(len(pairs), "properties ->", OUT)
