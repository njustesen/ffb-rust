"""Generate crates/ffb-model/src/factory/ruleset_skill_names.rs from the Java skill classes.

Java `SkillFactory.initialize(game)` registers, per game, every CONCRETE `Skill` subclass whose
`@RulesCollection` covers the game's rules (COMMON = all), keyed by `getName().toLowerCase()`;
`forName` is an exact lookup on that key (plus the "Ball & Chain" alias). The name comes from the
class's own `super("Name", ...)` or, for the stat-increase subclasses, from the abstract base
class it extends. This script extracts exactly that table so the Rust per-ruleset factory
(`SkillFactory::for_name_in` / `name_in`) is the Java registry, not a hand-kept spelling list.

Usage: python -I scripts/gen_ruleset_skill_names.py   (rewrites the .rs file; fails on a
duplicate key within one ruleset or a Java class with no Rust SkillId)
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = ROOT.parent / "ffb-java" / "ffb" / "ffb-common" / "src" / "main" / "java"
SKILL_DIR = JAVA / "com" / "fumbbl" / "ffb" / "skill"
SKILL_ID_RS = ROOT / "crates" / "ffb-model" / "src" / "enums" / "skill_id.rs"
OUT = ROOT / "crates" / "ffb-model" / "src" / "factory" / "ruleset_skill_names.rs"
RULES = ("BB2016", "BB2020", "BB2025")
RUST_RULES = {"BB2016": "Bb2016", "BB2020": "Bb2020", "BB2025": "Bb2025"}
# Java class simple name -> Rust SkillId variant, where the Rust `class_name()` spells it differently.
CLASS_ALIAS = {"Bloodlust": "BloodLust", "Claws": "Claw"}


def super_name(text: str):
    m = re.search(r'super\(\s*"((?:[^"\\]|\\.)*)"', text)
    return m.group(1).replace('\\"', '"') if m else None


def usage_type(text: str):
    m = re.search(r"super\([^;]*?SkillUsageType\.(\w+)", text, re.S)
    return m.group(1) if m else "REGULAR"


def camel(const: str) -> str:
    return "".join(p.capitalize() for p in const.lower().split("_"))


def main() -> int:
    rs = SKILL_ID_RS.read_text(encoding="utf-8")
    body = rs[rs.index("pub fn class_name(self)"):]
    body = body[: body.index("\n    }\n")]
    class_to_variant = {cls: var for var, cls in re.findall(r'SkillId::(\w+) => "([^"]+)"', body)}
    rows = {}
    usages = {}
    errors = 0
    for f in sorted(SKILL_DIR.rglob("*.java")):
        text = f.read_text(encoding="utf-8", errors="replace")
        if re.search(r"\babstract\s+class\b", text):
            continue
        anns = re.findall(r"@RulesCollection\(([^)]*)\)", text)
        rules = set()
        for a in anns:
            rules |= set(re.findall(r"Rules\.(BB\d{4})", a))
            if "Rules.COMMON" in a:
                rules |= set(RULES)
        if not rules:
            print(f"ERROR no @RulesCollection on concrete {f}")
            errors += 1
            continue
        name = super_name(text)
        if name is None:
            base = re.search(r"extends\s+com\.fumbbl\.ffb\.skill\.(\w+)", text)
            name = super_name((SKILL_DIR / f"{base.group(1)}.java").read_text(encoding="utf-8")) if base else None
        if name is None:
            print(f"ERROR no name for {f}")
            errors += 1
            continue
        cls = f.stem
        variant = class_to_variant.get(cls) or CLASS_ALIAS.get(cls)
        if variant is None:
            print(f"ERROR Java class {cls} has no Rust SkillId ({f})")
            errors += 1
            continue
        for r in rules:
            key = (r, name.lower())
            if key in rows and rows[key][1] != variant:
                print(f"ERROR duplicate {key}: {rows[key]} vs {(name, variant)}")
                errors += 1
            rows[key] = (name, variant)
            usages[(r, variant)] = usage_type(text)
    if errors:
        return 1
    lines = [
        "//! GENERATED by `scripts/gen_ruleset_skill_names.py` from the Java skill classes -- do not edit.",
        "//!",
        "//! Java `SkillFactory` per ruleset: (rules, `Skill.getName()`, Rust `SkillId`) for every concrete",
        "//! skill class whose `@RulesCollection` covers the rules (COMMON = all three).",
        "",
        "use crate::enums::{Rules, SkillId, SkillUsageType};",
        "",
        "pub const RULESET_SKILL_NAMES: &[(Rules, &str, SkillId)] = &[",
    ]
    for (r, _), (name, variant) in sorted(rows.items(), key=lambda kv: (kv[0][0], kv[0][1])):
        esc = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    (Rules::{RUST_RULES[r]}, "{esc}", SkillId::{variant}),')
    lines.append("];")
    lines.append("")
    lines.append("/// Java `Skill.getSkillUsageType()` of the ruleset's class (the `SkillUsageType` its constructor")
    lines.append("/// passes to `super(..)`; REGULAR when none): (rules, SkillId, usage type).")
    lines.append("pub const RULESET_SKILL_USAGE: &[(Rules, SkillId, SkillUsageType)] = &[")
    for (r, variant), usage in sorted(usages.items()):
        lines.append(f"    (Rules::{RUST_RULES[r]}, SkillId::{variant}, SkillUsageType::{camel(usage)}),")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for r in RULES:
        print(r, sum(1 for k in rows if k[0] == r))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
