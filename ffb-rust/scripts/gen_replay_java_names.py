"""Generate crates/ffb-parity/src/replay/java_names.rs (BACKLOG §O O3, the action records).

The harness's action records print Java ENUM CONSTANT names (`TurnMode.name()`,
`PlayerAction.name()`, `ReportId.name()` ...), while the game JSON and the Rust model carry the
`getName()` form. This script extracts, from the Java enum sources, the (constant, getName) pairs
of every enum the records need, so the Rust side maps getName -> constant exactly as Java declares
it (no CamelCase guessing).

It also embeds the per-ruleset REPORT CLASS table: which class each ruleset's `ReportFactory`
decodes a `ReportId` into, and that class's superclass chain (the records test
`instanceof ReportSkillRoll`, `mixed.ReportInjury` vs `bb2016.ReportInjury` ...). That table is an
ORACLE DUMP from the engine itself (harness `ReplayReportClassDump`, run on one replay per
ruleset):
    javac -cp D:/ffb_replays/ffb-ai-replay.jar -d <classes> .../ReplayReportClassDump.java
        .../ReplayStartDump.java .../FumbblReplayParser.java
    java -cp "<classes>;D:/ffb_replay_parity/bin/ffb-ai-replay-o1.jar"
        com.fumbbl.ffb.ai.simulation.ReplayReportClassDump D:/ffb_replays/fumbbl
        D:/ffb_replays/fumbbl_night_20261122 > report_classes.tsv

Usage: python -I scripts/gen_replay_java_names.py <report_classes.tsv>   (rewrites the .rs file)
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JAVA = ROOT.parent / "ffb-java" / "ffb" / "ffb-common" / "src" / "main" / "java" / "com" / "fumbbl" / "ffb"
OUT = ROOT / "crates" / "ffb-parity" / "src" / "replay" / "java_names.rs"
ENUMS = {
    "TURN_MODE": JAVA / "TurnMode.java",
    "WEATHER": JAVA / "Weather.java",
    "PLAYER_ACTION": JAVA / "PlayerAction.java",
    "DIRECTION": JAVA / "Direction.java",
    "SPECIAL_EFFECT": JAVA / "SpecialEffect.java",
    "REPORT_ID": JAVA / "report" / "ReportId.java",
}


def constants(path: Path):
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    body = text[text.index("{", text.index(" enum ")) + 1:]
    # The constant list ends at the first ';' outside a string literal.
    end, in_str = None, False
    for i, ch in enumerate(body):
        if ch == '"' and body[i - 1] != "\\":
            in_str = not in_str
        elif ch == ";" and not in_str:
            end = i
            break
    pairs = re.findall(r'\b([A-Z][A-Z0-9_]*)\s*\(\s*"((?:[^"\\]|\\.)*)"', body[:end])
    if not pairs:
        sys.exit(f"no constants in {path}")
    return pairs


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = [
        "//! GENERATED by `scripts/gen_replay_java_names.py` -- do not edit by hand.",
        "//!",
        "//! (Java enum constant, `getName()`) pairs of the enums the §O action records print by",
        "//! `name()`, and the per-ruleset report class table dumped from the engine's ReportFactory",
        "//! (harness `ReplayReportClassDump`): (ruleset, ReportId constant, class, superclass chain).",
        "",
    ]
    for const, path in ENUMS.items():
        pairs = constants(path)
        names = [n for _, n in pairs]
        if len(set(names)) != len(names):
            sys.exit(f"duplicate getName in {path}")
        out.append(f"/// `{path.stem}`: (constant, getName), declaration order.")
        out.append(f"pub const {const}: &[(&str, &str)] = &[")
        for c, n in pairs:
            out.append(f"    ({rust_str(c)}, {rust_str(n)}),")
        out.append("];")
        out.append("")
    rows = []
    for line in Path(sys.argv[1]).read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) != 4 or parts[0] not in ("BB2016", "BB2020", "BB2025"):
            continue
        rows.append(parts)
    if len(rows) != 3 * len(constants(ENUMS["REPORT_ID"])):
        sys.exit(f"report class table has {len(rows)} rows, expected 3 x ReportId")
    out.append("/// (ruleset, ReportId constant, report class canonical name or `NONE`, superclass chain).")
    out.append("pub const REPORT_CLASSES: &[(&str, &str, &str, &str)] = &[")
    for r in rows:
        out.append(f"    ({', '.join(rust_str(x) for x in r)}),")
    out.append("];")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} report class rows)")


if __name__ == "__main__":
    main()
